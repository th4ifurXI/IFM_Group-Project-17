const DICTS: Record<Lang, Dict> = { en, ms };

/** Map the engine's English verdict ("Convert now - ...", "Either - ...") to a key. */
export function verdictKey(verdict: string): V {
  const v = verdict.split(" - ")[0].trim();
  return v === "Convert now" ? "now" : v === "Convert later" ? "later" : "either";
}

interface Ctx { lang: Lang; t: Dict; setLang: (l: Lang) => void }
const LangContext = createContext<Ctx>({ lang: "en", t: en, setLang: () => {} });

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("lang");
    if (saved === "en" || saved === "ms") return saved;
  } catch { /* storage blocked: fall back to English */ }
  return "en";
}

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  useEffect(() => {
    document.documentElement.lang = lang === "ms" ? "ms" : "en";
    try { localStorage.setItem("lang", lang); } catch { /* ignore */ }
  }, [lang]);
  return <LangContext.Provider value={{ lang, t: DICTS[lang], setLang: setLangState }}>{children}</LangContext.Provider>;
}

export const useI18n = () => useContext(LangContext);
